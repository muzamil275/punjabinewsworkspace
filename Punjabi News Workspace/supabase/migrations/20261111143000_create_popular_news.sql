create table if not exists public.popular_news (
 id bigint generated by default as identity primary key,
 trend_date date not null,
 trend_key text not null,
 country text not null check (country in ('Pakistan','India')),
 google_query text not null,
 approx_traffic text,
 category text not null,
 title_en text not null,
 title_ur text not null,
 excerpt_en text not null,
 excerpt_ur text not null,
 source_name text not null,
 source_url text not null,
 image_url text,
 daily_rank integer not null check (daily_rank between 1 and 5),
 is_published boolean not null default false,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 constraint popular_news_date_trend_key unique (trend_date,trend_key)
);
create index if not exists popular_news_published_date_rank_idx on public.popular_news(trend_date desc,daily_rank asc) where is_published=true;
alter table public.popular_news enable row level security;
grant select on public.popular_news to anon,authenticated;
grant all on public.popular_news to service_role;
drop policy if exists "Published popular news is public" on public.popular_news;
create policy "Published popular news is public" on public.popular_news for select to anon,authenticated using (is_published=true);