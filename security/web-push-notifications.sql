-- Web Push subscription storage for Punjabi News Workspace.
-- Apply in the existing Supabase SQL editor before enabling browser notifications.
-- No anon/authenticated policies are intentionally created; server endpoints use the
-- server-only SUPABASE_SECRET_KEY / SUPABASE_SERVICE_ROLE_KEY and bypass RLS.
create table if not exists public.news_push_subscriptions (
  id bigint generated by default as identity primary key,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  language text not null default 'en' check (language in ('en','ur')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists news_push_subscriptions_created_at_idx
  on public.news_push_subscriptions (created_at);
alter table public.news_push_subscriptions enable row level security;
revoke all on table public.news_push_subscriptions from anon, authenticated;
grant all on table public.news_push_subscriptions to service_role;
